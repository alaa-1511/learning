-- Apply Policies

-- Courses
CREATE POLICY "Public courses viewable" ON public.courses FOR SELECT USING (true);
CREATE POLICY "Auth users insert courses" ON public.courses FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Auth users update courses" ON public.courses FOR UPDATE USING (auth.role() = 'authenticated');
CREATE POLICY "Auth users delete courses" ON public.courses FOR DELETE USING (auth.role() = 'authenticated');

-- Profiles
CREATE POLICY "Public profiles are viewable by everyone." ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Users can insert their own profile." ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "Users can update own profile." ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- Exams & Assignments
CREATE POLICY "Public exams viewable" ON public.exams FOR SELECT USING (true);
CREATE POLICY "Auth users manage exams" ON public.exams FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Public exam parts viewable" ON public.exam_parts FOR SELECT USING (true);
CREATE POLICY "Auth users manage exam parts" ON public.exam_parts FOR ALL USING (auth.role() = 'authenticated');

