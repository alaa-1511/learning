-- Function to handle NEW user signups
CREATE OR REPLACE FUNCTION public.handle_new_user() 
RETURNS trigger AS $$
DECLARE
  meta_data jsonb;
  full_name text;
BEGIN
  BEGIN
    meta_data := CAST(new.raw_user_meta_data AS jsonb);
  EXCEPTION WHEN OTHERS THEN
    meta_data := '{}'::jsonb; 
  END;
  full_name := COALESCE(
    meta_data->>'name', 
    (meta_data->>'firstName' || ' ' || (meta_data->>'lastName')),
    ''
  );
  INSERT INTO public.profiles (id, email, first_name, last_name, name, is_subscribed)
  VALUES (
    new.id, 
    new.email, 
    meta_data->>'firstName', 
    meta_data->>'lastName',
    full_name,
    COALESCE((meta_data->>'isSubscribed')::boolean, false)
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function to handle UPDATED users
CREATE OR REPLACE FUNCTION public.handle_user_update() 
RETURNS trigger AS $$
DECLARE
  meta_data jsonb;
  full_name text;
BEGIN
  BEGIN
    meta_data := CAST(new.raw_user_meta_data AS jsonb);
  EXCEPTION WHEN OTHERS THEN
    meta_data := '{}'::jsonb;
  END;
  full_name := COALESCE(
    meta_data->>'name', 
    (meta_data->>'firstName' || ' ' || (meta_data->>'lastName')),
    ''
  );
  UPDATE public.profiles
  SET 
    email = new.email,
    first_name = meta_data->>'firstName',
    last_name = meta_data->>'lastName',
    name = full_name,
    is_subscribed = COALESCE((meta_data->>'isSubscribed')::boolean, false)
  WHERE id = new.id;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Triggers
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

DROP TRIGGER IF EXISTS on_auth_user_updated ON auth.users;
CREATE TRIGGER on_auth_user_updated
  AFTER UPDATE ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_user_update();

